use nanoserde::DeJson;

/// Minimal view of `extension_api.json`: only the engine class names are needed.
#[derive(DeJson)]
struct JsonApi {
    classes: Vec<JsonClass>,
}

#[derive(DeJson)]
struct JsonClass {
    name: String,
}

fn main() {
    godot_bindings::emit_godot_version_cfg();
    generate_engine_classes();
}

/// Writes a sorted list of all Godot engine class names to `OUT_DIR/engine_classes.rs`.
///
/// `#[class(base = X)]` needs to distinguish engine classes (which live in `godot::classes`) from user-declared classes (which live in the
/// user's own crate). Since proc-macros cannot resolve names, the decision is made by looking up `X` in this list.
fn generate_engine_classes() {
    let mut watch = godot_bindings::StopWatch::start();
    let json = godot_bindings::load_extension_api_json(&mut watch);

    let api = JsonApi::deserialize_json(json.as_ref())
        .unwrap_or_else(|e| panic!("failed to parse extension_api.json: {e}"));

    let mut names: Vec<String> = api
        .classes
        .into_iter()
        .map(|class| to_rust_class_name(&class.name))
        .collect();
    names.sort_unstable();
    names.dedup();

    let mut code = String::from(
        "// This file is generated by godot-macros/build.rs; do not edit.\n\
         /// All Godot engine class names, sorted for binary search.\n\
         pub(crate) const ENGINE_CLASS_NAMES: &[&str] = &[\n",
    );
    for name in &names {
        code.push_str("    \"");
        code.push_str(name);
        code.push_str("\",\n");
    }
    code.push_str("];\n");

    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR not set");
    let out_file = std::path::Path::new(&out_dir).join("engine_classes.rs");
    std::fs::write(&out_file, code)
        .unwrap_or_else(|e| panic!("failed to write {}: {e}", out_file.display()));
}

/// Converts a Godot class name to the Rust type name used in `godot::classes`, e.g. `HTTPRequest` -> `HttpRequest`.
///
/// Mirrors `godot_codegen::conv::to_pascal_case()`; keep both in sync. A mismatch only means that `#[class(base = X)]` misclassifies `X`,
/// which surfaces as a compile error and can be worked around by writing the base as a path.
fn to_rust_class_name(godot_name: &str) -> String {
    use heck::ToPascalCase;

    // Special cases, mirroring `to_snake_special_case()` in godot-codegen.
    let special = match godot_name {
        "JSONRPC" => Some("json_rpc"),
        "OpenXRAPIExtension" => Some("open_xr_api_extension"),
        "OpenXRIPBinding" => Some("open_xr_ip_binding"),
        _ => None,
    };

    if let Some(special) = special {
        return special.to_pascal_case();
    }

    godot_name
        .to_pascal_case()
        .replace("GdExtension", "GDExtension")
        .replace("GdNative", "GDNative")
        .replace("GdScript", "GDScript")
        .replace("Vsync", "VSync")
        .replace("Sdfgiy", "SdfgiY")
}
